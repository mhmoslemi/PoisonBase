#!/usr/bin/env python3
"""Audit the September 21 batches and regenerate their LaTeX tables (stdlib only)."""
import csv
from decimal import Decimal, ROUND_HALF_UP
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import re
import statistics

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / 'tables'
SCORE = ROOT / 'score_alternatives_8x6_20260921_result'
TINY = ROOT / 'tinyimagenet20_gm_8x6_20260921_result_yiweilu'
SELECTORS = ['classifier', 'classifier-norm', 'target-margin', 'similarity-target-margin', 'confidence']
LABELS = ['Classifier-only alignment', 'Normalized classifier alignment', 'Target-class margin', 'Similarity + target-class margin', 'Confidence-only']
SETTINGS = [('fc', .001), ('fc', .002), ('gradmatch', .001), ('gradmatch', .002), ('gradmatch', .005), ('sapa', .001), ('sapa', .002), ('sapa', .005)]
TARGETS = {'fc': [2540, 8129, 3725, 5705, 7663, 3875, 5169, 6335],
           'gradmatch': [843, 1257, 8252, 8730, 8055, 5859, 8954, 821]}
ERROR = re.compile(r'Traceback|CUDA out of memory|TIME LIMIT|CANCELLED|Killed|Error:')
SOURCES = {}


def read(path):
    raw = path.read_bytes()
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(raw).hexdigest()
    return raw.decode()


def number(x, digits=1):
    if isinstance(x, Fraction):
        value = Decimal(x.numerator) / Decimal(x.denominator)
    else:
        value = Decimal(str(x))
    return f'{value.quantize(Decimal(10) ** -digits, rounding=ROUND_HALF_UP):.{digits}f}'


def require(ok, message):
    if not ok:
        raise ValueError(message)


def audit_run(path, targets, summary, tiny=False):
    rows = list(csv.DictReader(read(path).splitlines()))
    keys = [(int(r['target_idx']), int(r['victim_id'])) for r in rows]
    expected = {(t, v) for t in targets for v in range(6)}
    require(len(rows) == 48 and len(set(keys)) == 48 and set(keys) == expected, f'{path}: missing/duplicate trials')
    for row in rows:
        require(row['success'] in ('0', '1'), f'{path}: invalid success')
        require(0 <= float(row['clean_test_acc']) <= 1, f'{path}: invalid accuracy')
        require(0 <= float(row['realized_linf']) <= 8/255 + 1e-6, f'{path}: invalid perturbation')
        if tiny:
            individual = path.parent / f'target_{row["target_idx"]}_victim_{row["victim_id"]}.json'
            payload = json.loads(read(individual))
            for key, value in payload.items():
                require(str(value) == row[key], f'{individual}: differs from CSV: {key}')
    successes = sum(int(r['success']) for r in rows)
    target_rates = [statistics.mean(int(r['success']) for r in rows if int(r['target_idx']) == t) for t in targets]
    accuracy = statistics.mean(float(r['clean_test_acc']) for r in rows)
    std = statistics.pstdev(target_rates)
    for actual, saved in [(successes/48, summary['asr_mean']), (std, summary['asr_std']),
                          (accuracy, summary['clean_test_acc' if tiny else 'cta_post_mean'])]:
        require(math.isclose(actual, saved, abs_tol=1e-12), f'{path}: summary disagrees with trial data')
    require(summary['num_trials'] == 48 and summary['num_targets'] == 8, f'{path}: wrong trial count')
    return dict(successes=successes, trials=48, targets=targets, asr_pct=successes*100/48,
                asr_target_population_sd_pct=100*std, clean_accuracy_pct=100*accuracy,
                source=str(path.relative_to(ROOT)))


def audit_logs(pattern, expected_count, final_marker=None):
    paths = sorted((ROOT / 'sbatch/logs').glob(pattern))
    require(len(paths) == expected_count, f'Unexpected log count for {pattern}: {len(paths)}')
    for path in paths:
        text = read(path)
        require(not ERROR.search(text), f'Failure marker in {path}')
        if final_marker:
            require(final_marker in text, f'Completion marker missing from {path}')
    return [str(p.relative_to(ROOT)) for p in paths]


def highlight(value, column):
    ranks = sorted(set(column), reverse=True)
    text = number(value)
    if value == ranks[0]:
        return r'\textbf{' + text + '}'
    if len(ranks) > 1 and value == ranks[1]:
        return r'\underline{' + text + '}'
    return text


def score_table(rows, caption, label, split=None):
    lines = [r'% Generated by tools/build_appendix_result_tables.py; do not edit numbers manually.',
             r'\begin{table*}[t]', r'\centering', r'\caption{' + caption + '}',
             r'\label{' + label + '}', r'\vspace{-0.6em}',
             r'\resizebox{\textwidth}{!}{%', r'\begin{tabular}{@{}l *{8}{c}@{}}', r'\toprule',
             r'& \multicolumn{8}{c}{ConvNet} \\', r'\cmidrule(l){2-9}',
             r'& \multicolumn{2}{c}{BP} & \multicolumn{3}{c}{GM} & \multicolumn{3}{c}{SAPA} \\',
             r'\cmidrule(lr){2-3}\cmidrule(lr){4-6}\cmidrule(l){7-9}',
             r'\textbf{Method} $\boldsymbol{\rho}$ (\%) & 0.1 & 0.2 & 0.1 & 0.2 & 0.5 & 0.1 & 0.2 & 0.5 \\', r'\midrule']
    columns = list(zip(*(values for _, values in rows)))
    for index, (name, values) in enumerate(rows):
        if split is not None and index in (0, split):
            if index:
                lines.append(r'\midrule')
            block = 'Previously reported ablation (not rerun)' if index == 0 else r'New experiments ($8$ targets $\times$ $6$ victims)'
            lines += [r'\multicolumn{9}{@{}l}{\emph{' + block + r'}} \\', r'\addlinespace[2pt]']
        lines.append(name + ' & ' + ' & '.join(highlight(v, col) for v, col in zip(values, columns)) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}%', '}', r'\vspace{-0.5em}', r'\end{table*}', '']
    return '\n'.join(lines)


def historical_rows():
    text = '\n'.join(line for line in read(ROOT / 'abaltion_diff.tex').splitlines()
                     if not line.lstrip().startswith('%'))
    labels = [r'\textsc{Rand}', '$R$', '$M$', r'$\langle g_i,g_t\rangle$', r'\textsc{Basis}']
    rows = []
    for label in labels:
        match = re.search(re.escape(label) + r'\s*&\s*(.*?)\\\\', text, re.S)
        require(match is not None, f'Missing historical row {label}')
        cells = match[1].split('&')
        require(len(cells) == 18, 'Historical table layout changed')
        values = [Fraction(re.search(r'\d+(?:\.\d+)?', cell)[0]) for cell in cells[:8]]
        rows.append((label, values))
    return rows


def main():
    records, rates = [], {}
    manifest = list(csv.DictReader(read(ROOT / 'sbatch/score_alternatives_8x6_20260921/manifest.tsv').splitlines(), delimiter='\t'))
    require(len(manifest) == 40, 'Expected 40 score cells')
    for entry in manifest:
        cell = SCORE / ('cell_' + entry['id'])
        paths = list(cell.glob('*/results.csv'))
        require(len(paths) == 1, f'{cell}: ambiguous result files')
        path = paths[0]
        summary = json.loads(read(path.with_name('summary.json')))
        protocol = json.loads(read(cell / 'protocol.json'))
        attack, budget, selector = entry['attack'], float(entry['budget']), entry['selector']
        targets = TARGETS['fc' if attack == 'fc' else 'gradmatch']
        require(protocol['target_indices'] == targets, 'Target pinning mismatch')
        for key, value in dict(dataset='CIFAR10', model='ConvNetBN', class_pair='dog-bird',
                               seed=42, num_targets=8, num_victims=6, num_surrogates=20,
                               craft_ensemble=5, attack=attack, budget=budget,
                               sel_component=selector, victim_epochs=50).items():
            require(protocol[key] == value, f'{cell}: protocol mismatch for {key}')
        for key, value in dict(attack=attack, budget=budget, sel_component=selector).items():
            require(summary[key] == value, f'{cell}: summary identity mismatch')
        record = audit_run(path, targets, summary)
        record.update(cell=entry['id'], attack=attack, budget=budget, selector=selector)
        record['logs'] = audit_logs('score' + entry['id'] + '_*.out', 1,
                                   'Verified 8 pinned targets x 6 victims = 48 unique evaluations.')
        records.append(record)
        rates[selector, attack, budget] = Fraction(record['successes'] * 100, 48)
    rows = [(label, [rates[selector, attack, budget] for attack, budget in SETTINGS])
            for selector, label in zip(SELECTORS, LABELS)]
    common = (r'ASR (\%) on CIFAR-10 using ConvNetBN, with dog as the poison class and bird as the target class. '
              r'BP denotes the code\textquotesingle s \texttt{fc} attack in sample mode. '
              r'Best and second-best values per column are \textbf{bold} and \underline{underlined}, including ties.')
    # Avoid requiring a textcomp-specific apostrophe macro in the paper preamble.
    common = common.replace(r'code\textquotesingle s', "code's")
    (TABLES / 'score_alternatives.tex').write_text(score_table(rows,
        r'Additional scoring alternatives. Each entry uses the same eight pinned targets and six victims per target within an attack (48 trials); $\epsilon=8/255$. ' + common,
        'tab:score-alternatives-8x6'))
    old = historical_rows()
    (TABLES / 'score_alternatives_with_reference.tex').write_text(score_table(old + rows,
        r'Extended scoring comparison. The first block reproduces the existing ablation; these baselines were not rerun under the new $8\times6$ protocol. '
        r'The second block reports the new 48-trial results. Cross-block comparisons are descriptive, not matched reruns. ' + common,
        'tab:score-alternatives-reference', split=5))
    tiny_manifest = json.loads(read(TINY / 'manifest.json'))
    tiny_targets = json.loads(read(TINY / 'targets.json'))
    require(tiny_manifest['fingerprint'] == tiny_targets['fingerprint'], 'Tiny target fingerprint mismatch')
    require(len(tiny_manifest['classes']) == 20 and len(tiny_manifest['train']) == 4000
            and len(tiny_manifest['val']) == 1000 and tiny_manifest['num_poisons'] == 8, 'Wrong Tiny subset')
    targets = [r['index'] for r in tiny_targets['targets']]
    require(len(targets) == len(set(targets)) == 8, 'Wrong Tiny targets')
    tiny_records = []
    for method in ['random', 'minus-m', 'basis']:
        summary = json.loads(read(TINY / method / 'summary.json'))
        require(summary['fingerprint'] == tiny_manifest['fingerprint']
                and summary['protocol'] == tiny_manifest['protocol'], 'Tiny protocol mismatch')
        record = audit_run(TINY / method / 'results.csv', targets, summary, tiny=True)
        record['method'] = method
        tiny_records.append(record)
    logs = audit_logs('tiny20_*.out', 8)
    for record in tiny_records:
        log = next(p for p in logs if '/tiny20_experiment_' + record['method'] + '-' in p)
        completed = re.findall(r'victim_(\d+)_(\d+)\.pt: epoch 30/30 complete', read(ROOT / log))
        require({(int(t), int(v)) for t, v in completed} == {(t, v) for t in targets for v in range(6)}, 'Tiny epoch completion mismatch')
    tiny_rates = [Fraction(r['successes']*100, 48) for r in tiny_records]
    lines = [r'% Generated by tools/build_appendix_result_tables.py.', r'\begin{table}[t]', r'\centering',
        r'\caption{GM on a fixed TinyImageNet-20 subset: 20 classes, 200 training images per class (4,000 total), and 1,000 validation images. '
        r'ResNet18 with a small-image stem is trained from scratch for 30 epochs at $64\times64$. '
        r'Three clean surrogates are shared across methods; $\rho=0.2\%$ (8 poisons), $\epsilon=8/255$. '
        r'Each method uses the same eight targets and six victim seeds per target. ASR is the mean $\pm$ population standard deviation across eight per-target success rates. '
        r'Accuracy is mean clean validation accuracy after poisoned training. Best and second-best ASR are \textbf{bold} and \underline{underlined}.}',
        r'\label{tab:tinyimagenet20-gm}', r'\vspace{-0.5em}', r'\small',
        r'\begin{tabular}{@{}lccc@{}}', r'\toprule',
        r'\textbf{Method} & ASR (\%) & Successes & Accuracy (\%) \\', r'\midrule']
    for label, record, rate in zip([r'\textsc{Rand}', '$M$', r'\textsc{Basis}'], tiny_records, tiny_rates):
        lines.append(label + ' & ' + highlight(rate, tiny_rates) + r' $\pm$ ' + number(record['asr_target_population_sd_pct'])
                     + f' & {record["successes"]}/48 & ' + number(record['clean_accuracy_pct'], 2) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\vspace{-0.5em}', r'\end{table}', '']
    (TABLES / 'tinyimagenet20_gm.tex').write_text('\n'.join(lines))
    report = dict(score_runs=records, tiny_runs=tiny_records, tiny_logs=logs,
                  total_trials=sum(r['trials'] for r in records + tiny_records),
                  historical_reference=dict(source='abaltion_diff.tex', independently_recomputed=False,
                      values={label: [float(v) for v in values] for label, values in old}),
                  rounding='Decimal ROUND_HALF_UP, one decimal ASR; two decimals accuracy',
                  source_sha256=SOURCES)
    (TABLES / 'appendix_results_audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'Validated {len(records)} score cells + {len(tiny_records)} Tiny methods; {report["total_trials"]} trials; 48 logs. Wrote three LaTeX tables and audit JSON.')


if __name__ == '__main__':
    main()
